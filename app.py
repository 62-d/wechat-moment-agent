# -------------------------------------------------------------------------

# 优先从环境变量读取，如果没有则从 st.secrets 读取（用于云端部署）
api_key = os.environ.get("DEEPSEEK_API_KEY")
if api_key is None:
    # 云端部署时使用 st.secrets
    api_key = st.secrets["DEEPSEEK_API_KEY"]

client = OpenAI(
    api_key=api_key,
    base_url="https://api.deepseek.com"
)


def generate_post(topic):
    response = client.chat.completions.create(
        model="deepseek-chat",
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": topic}
        ],
        temperature=0.8,
    )
    return response.choices[0].message.content

# ---------- 页面 UI ----------
st.set_page_config(page_title="朋友圈文案生成器", page_icon="📝")
st.title("📝 朋友圈文案生成器")
st.write("输入一个心情或主题，AI 帮你写四种风格的文案")

topic = st.text_input("主题词", placeholder="例如：加班、下雨、吃了顿好的、失恋了")

if st.button("生成文案"):
    if topic:
        with st.spinner("AI 创作中..."):
            result = generate_post(topic)
        # 把 --- 换成换行+分割线，让显示更好看
        formatted_result = result.replace("---", "\n\n---\n\n")
        st.markdown(formatted_result)
    else:
        st.warning("请输入主题词")